/// Noise functions generating the terrain elevations of a complex planetary surface.
///
/// Port of noise-rs' complex planet example, itself a port of libnoise's.
///
/// The terrain elevations are generated by a collection of over a hundred
/// noise functions in a hierarchy of groups and subgroups. Each group and
/// subgroup outputs a single output value that originates from a caching
/// module (`noise::modules::Cache`). Each group and subgroup can be thought of
/// as a single complex noise function that can be used as a source function for
/// other noise functions. The caching module was chosen as the source of the
/// output value to prevent costly recalculations by each group and subgroup
/// requesting an output value from it.
///
/// See `SubGroupId` for the list of module groups and subgroups that build the
/// planet's terrain.
///
/// Building it is cheap: no noise value is computed until sampled.
pub struct PlanetGraph {
    continents: ContinentGroup,
    terrain_type: TerrainTypeGroup,
    mountainous: MountainousGroup,
    hilly: HillyGroup,
    plains: PlainsGroup,
    badlands: BadlandsGroup,
    rivers: RiverPositionsGroup,
    scaled: ScaledTerrainGroup,
    final_planet: FinalPlanetGroup,
}

impl PlanetGraph {
    pub fn build(settings: &MapGeneratorSettings) -> Self {
        let continents = ContinentGroup::build(settings);
        let terrain_type = TerrainTypeGroup::build(settings, &continents);
        let mountainous = MountainousGroup::build(settings);
        let hilly = HillyGroup::build(settings);
        let plains = PlainsGroup::build(settings);
        let badlands = BadlandsGroup::build(settings);
        let rivers = RiverPositionsGroup::build(settings);
        let scaled = ScaledTerrainGroup::build(settings, &mountainous, &hilly, &plains, &badlands);
        let final_planet =
            FinalPlanetGroup::build(settings, &continents, &terrain_type, &scaled, &rivers);
        Self {
            continents,
            terrain_type,
            mountainous,
            hilly,
            plains,
            badlands,
            rivers,
            scaled,
            final_planet,
        }
    }

    /// Output of the whole graph, in planetary elevation units
    /// (-1.0 for the lowest underwater trenches and +1.0 for the highest mountain peaks).
    pub fn unscaled_final_planet(&self) -> &NoiseNode {
        &self.final_planet.unscaled_final_planet
    }

    pub fn node(&self, id: SubGroupId) -> &NoiseNode {
        match id {
            SubGroupId::BaseContinentDef => &self.continents.base_continent_def,
            SubGroupId::ContinentDef => &self.continents.continent_def,
            SubGroupId::TerrainTypeDef => &self.terrain_type.terrain_type_def,
            SubGroupId::MountainBaseDef => &self.mountainous.mountain_base_def,
            SubGroupId::MountainousHigh => &self.mountainous.mountainous_high,
            SubGroupId::MountainousLow => &self.mountainous.mountainous_low,
            SubGroupId::MountainousTerrain => &self.mountainous.mountainous_terrain,
            SubGroupId::HillyTerrain => &self.hilly.hilly_terrain,
            SubGroupId::PlainsTerrain => &self.plains.plains_terrain,
            SubGroupId::BadlandsSand => &self.badlands.badlands_sand,
            SubGroupId::BadlandsCliffs => &self.badlands.badlands_cliffs,
            SubGroupId::BadlandsTerrain => &self.badlands.badlands_terrain,
            SubGroupId::RiverPositions => &self.rivers.river_positions,
            SubGroupId::ScaledMountainousTerrain => &self.scaled.scaled_mountainous_terrain,
            SubGroupId::ScaledHillyTerrain => &self.scaled.scaled_hilly_terrain,
            SubGroupId::ScaledPlainsTerrain => &self.scaled.scaled_plains_terrain,
            SubGroupId::ScaledBadlandsTerrain => &self.scaled.scaled_badlands_terrain,
            SubGroupId::ContinentalShelf => &self.final_planet.continental_shelf,
            SubGroupId::BaseContinentElev => &self.final_planet.base_continent_elev,
            SubGroupId::ContinentsWithPlains => &self.final_planet.continents_with_plains,
            SubGroupId::ContinentsWithHills => &self.final_planet.continents_with_hills,
            SubGroupId::ContinentsWithMountains => &self.final_planet.continents_with_mountains,
            SubGroupId::ContinentsWithBadlands => &self.final_planet.continents_with_badlands,
            SubGroupId::ContinentsWithRivers => &self.final_planet.continents_with_rivers,
            SubGroupId::UnscaledFinalPlanet => &self.final_planet.unscaled_final_planet,
        }
    }
}
